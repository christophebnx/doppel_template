"""Regenerate the compact `_index.md` files (one line per item) from frontmatter.

  index.py            regenerate all indexes
  index.py --check    exit 1 if an index is stale (used by tests / curator)

Indexes: tasks, projects, outbox, inbox (pending), inbox/_processed. A domain module adds its own index function
to INDEXES (one line per item, from frontmatter).
Agents read the index first and open only the files they need. Never edit indexes by hand.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from common import OPEN_STATUSES, get_root, load_config, load_tasks, parse_date, read_md

GENERATED = "<!-- generated by scripts/index.py — do not edit by hand -->"
PRIO_ORDER = {"P1": 0, "P2": 1, "P3": 2}


def _fm(path: Path) -> dict:
    try:
        return read_md(path)[0]
    except Exception:  # malformed file: still index it by name
        return {}


def _doc(title: str, columns: str, lines: list[str]) -> str:
    body = "\n".join(lines) if lines else "_(vide)_"
    return f"# {title}\n{GENERATED}\n`{columns}`\n\n{body}\n"


def tasks_index(root: Path) -> str:
    tasks = list(load_tasks(root).values())

    def key(t):
        dl = t.deadline_date
        return (0 if t.is_open else 1, PRIO_ORDER.get(t.meta.get("priority"), 9), str(dl or "9999"), t.id)

    lines = []
    for t in sorted(tasks, key=key):
        m = t.meta
        est = f"{m.get('estimate_h')}h" if m.get("estimate_h") is not None else "?h"
        lines.append(" · ".join(str(x) for x in (
            t.id, m.get("project") or "-", t.status, m.get("priority") or "-", m.get("executor") or "-", est,
            parse_date(m.get("deadline")) or "-", m.get("title") or "")))
    return _doc("Tâches", "id · projet · statut · prio · executor · estimation · échéance · titre", lines)


def projects_index(root: Path) -> str:
    cfg = load_config(root)
    tasks = load_tasks(root).values()
    slugs = sorted(set(cfg["projects"]) | {p.name for p in (root / "projects").glob("*") if p.is_dir()})
    lines, archived = [], []
    for s in slugs:
        pc = cfg["projects"].get(s) or {}
        if pc.get("archived"):
            archived.append(f"{s} ({pc['archived']}) → archive/projects/{s}/")
            continue
        n_open = sum(1 for t in tasks if t.meta.get("project") == s and t.status in OPEN_STATUSES)
        lines.append(" · ".join(str(x) for x in (
            s, pc.get("name") or "-", "actif" if pc.get("active", True) else "inactif", f"{n_open} tâches ouvertes")))
    doc = _doc("Projets", "slug · nom · état · tâches ouvertes", lines)
    return doc + (f"\nArchivés : {'; '.join(archived)}\n" if archived else "")


def outbox_index(root: Path) -> str:
    lines = []
    for p in sorted((root / "outbox").glob("*.md")):
        if p.name.startswith("_"):
            continue
        m = _fm(p)
        lines.append(" · ".join(str(x) for x in (
            p.name, m.get("state") or "draft", m.get("task") or "-", m.get("project") or "-",
            m.get("title") or (f"status {m['audience']}" if m.get("audience") else ""))))
    return _doc("Outbox (en attente de validation)", "fichier · état · tâche · projet · titre", lines)


def inbox_index(root: Path, sub: str, title: str) -> str:
    lines = []
    folder = root / "inbox" / sub if sub else root / "inbox"
    for p in sorted(folder.glob("*.md")):
        if p.name.startswith("_"):
            continue
        m = _fm(p)
        lines.append(" · ".join(str(x) for x in (
            p.name, m.get("type") or "-", m.get("from") or "-", m.get("project_hint") or "-")))
    return _doc(title, "fichier · type · de · projet", lines)


# index file (repo-relative) -> builder. Domain modules register their folders here.
INDEXES = {
    "tasks/_index.md": tasks_index,
    "projects/_index.md": projects_index,
    "outbox/_index.md": outbox_index,
    "inbox/_index.md": lambda root: inbox_index(root, "", "Inbox — à traiter"),
    "inbox/_processed/_index.md": lambda root: inbox_index(root, "_processed", "Inbox — traités"),
}


def build_all(root: Path) -> dict[Path, str]:
    return {root / rel: fn(root) for rel, fn in INDEXES.items()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    root = get_root(args.root)
    stale = []
    for path, content in build_all(root).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(root))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if args.check:
        print("stale: " + ", ".join(map(str, stale)) if stale else "indexes up to date")
        return 1 if stale else 0
    print("updated: " + (", ".join(map(str, stale)) or "nothing"))
    return 0


if __name__ == "__main__":
    from common import run_main
    sys.exit(run_main(main, __file__))
